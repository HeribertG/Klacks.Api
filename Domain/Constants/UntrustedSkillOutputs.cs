/// <summary>
/// Curated set of skills whose results carry content authored OUTSIDE this system: web pages, e-mail
/// bodies and headers, chat messages. Their results are framed as untrusted when fed back into the LLM
/// loop so the model treats them as data instead of as instructions (prompt-injection defense).
/// Curated by name — mirroring the <c>SkillRiskClassifier.SensitiveSkills</c> precedent — because the
/// classification must also cover plugin skills that are seeded from JSON and therefore have no C#
/// implementation class or compile-time descriptor to annotate. A name heuristic is deliberately not
/// used: a future skill named <c>read_*</c> or <c>list_*</c> that reads internal data only would be
/// mislabeled, and worse, a renamed untrusted skill would silently lose the flag.
/// <c>UntrustedSkillOutputsCatalogueTests</c> guards every entry against skill renames.
/// list_macros is listed as well: macro names and scripts are free text written by administrators, imported by the
/// region setup or generated by the assistant itself, so a script comment could carry instructions to the model.
/// get_client_details is listed because it returns the free-text client notes.
/// Free text that users below the administrator can write is listed too (schedule notes, break and work
/// information, expense descriptions, memories, navigation utterances, shift, group and scenario descriptions), because
/// it is the realistic planner-to-administrator injection path. Person names and addresses are deliberately NOT listed:
/// they appear in almost every result, so marking them would put the banner on nearly every turn and wear down its signal.
/// list_groups and list_groups_hierarchical do not return group descriptions at all (they run on practically every
/// group-scoped turn, so flagging them would wear down the banner); the description is read only where it is flagged
/// (get_group_details).
/// <c>UntrustedSkillOutputsCompletenessGuardTests</c> fails when a read skill projects a free-text property and is neither
/// listed here nor justified in its allowlist.
/// </summary>

namespace Klacks.Api.Domain.Constants;

public static class UntrustedSkillOutputs
{
    private static readonly HashSet<string> Names = new(StringComparer.OrdinalIgnoreCase)
    {
        // Search results from the open internet: title, snippet and URL are attacker-controlled text.
        "web_search",
        // E-mail subject, sender and body come from whoever sent the mail.
        "read_email",
        "fetch_new_emails",
        "translate_email",
        "list_emails",
        "list_emails_by_client",
        "list_emails_by_group",
        // Derived from an e-mail body, so it inherits the sender's text (summary, quoted content).
        "get_email_analysis",
        // Derived from a messenger message body, so it inherits the external sender's text.
        "get_messenger_analysis",
        // Messaging plugin: message bodies written by other users or relayed from external channels.
        "read_messages",
        // Messaging plugin: setup diagnosis quotes unknown senders' display names and vendor error texts.
        "diagnose_messaging_setup",
        // Pending notes relay scheduled-task results and inbound-message notices (sender names, subjects).
        "manage_pending_notes",
        // Delivered notes carry the same relayed external text as pending notes.
        "recall_delivered_notes",
        "list_macros",
        // Client notes are free text typed in by any planner (the notes right is part of the Planer floor), so a
        // note can carry instructions to the model.
        "get_client_details",
        // Schedule note text is free text any planner can type (editing notes is part of the Planer floor).
        "list_schedule_notes",
        // Break and absence information is a free-text field planners type on every break, placeholder and bulk absence.
        "search_client_absences",
        // Expense descriptions are free text written by planners (add_expense and update_expense sit in the Planer floor).
        "list_expenses",
        // Work and work-change descriptions come from the free-text information field planners type when placing work.
        "read_schedule_state",
        // Personal memories (add_personal_memory has no gate) and automatically extracted chat memories carry user-typed text.
        "get_ai_memories",
        // Navigation feedback stores the raw utterances of every user who searched the application.
        "list_navigation_feedback",
        // Shift descriptions are free text written by supervisors with the shift-editing right.
        "get_shift_details",
        // Group descriptions are free text written by supervisors with the group-editing right.
        "get_group_details",
        // Scenario names and descriptions are free text typed in by whoever creates a scenario.
        "list_scenarios",
        // Skill descriptions are generated by the model (create_agent_skill) from a turn that may itself have been injected.
        "list_agent_skills"
    };

    public static bool Contains(string? skillName) =>
        !string.IsNullOrEmpty(skillName) && Names.Contains(skillName);

    public static IReadOnlyCollection<string> All => Names;
}
